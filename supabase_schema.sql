-- Phodio / Soulprint PostgreSQL schema for Supabase
-- Run this entire file in Supabase SQL Editor.
-- It preserves the existing table names and sample records from studio_mgmt.sql.

CREATE TABLE IF NOT EXISTS admin (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(100),
    lastname VARCHAR(100),
    username VARCHAR(150) UNIQUE,
    phone VARCHAR(11) UNIQUE,
    password VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    profile_image VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS bookings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    title VARCHAR(255) NOT NULL,
    service_type VARCHAR(80),
    package_key VARCHAR(80),
    package_type VARCHAR(100),
    motif VARCHAR(100),
    price NUMERIC(10,2),
    booking_date DATE,
    start_time TIME,
    slot_period VARCHAR(2) CHECK (slot_period IN ('AM','PM') OR slot_period IS NULL),
    color_code VARCHAR(7),
    attendee_count SMALLINT NOT NULL DEFAULT 1 CHECK (attendee_count >= 0),
    client_notes TEXT,
    status VARCHAR(32) NOT NULL DEFAULT 'Confirmed',
    status_note TEXT,
    status_updated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT booking_day_slot UNIQUE (booking_date, slot_period)
);

CREATE INDEX IF NOT EXISTS bookings_client_status ON bookings (client_id, status);
CREATE INDEX IF NOT EXISTS bookings_date_status ON bookings (booking_date, status);

CREATE TABLE IF NOT EXISTS booking_updates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL,
    note TEXT NOT NULL,
    actor_type VARCHAR(10) NOT NULL DEFAULT 'system' CHECK (actor_type IN ('client','admin','system')),
    actor_id INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS booking_updates_booking_id ON booking_updates (booking_id);

CREATE TABLE IF NOT EXISTS daily_tracker (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_date DATE NOT NULL UNIQUE,
    income_today NUMERIC(10,2) NOT NULL,
    client_today INTEGER NOT NULL,
    target NUMERIC(10,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS expenses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    amount NUMERIC(10,2) NOT NULL,
    expense_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS liabilities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creditor VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    amount NUMERIC(10,2) NOT NULL,
    due_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

